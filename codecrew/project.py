"""What CodeCrew learns about a project before verifying it.

A generated workspace is flat and self-contained. A developer's repository
is not: code under ``src/``, dependencies declared in ``pyproject.toml`` or
``requirements*.txt``, and opinions about thresholds. This module reads all
of that once, so the gates judge the project as its author runs it rather
than failing it for environment reasons that say nothing about the code.

Configuration, in increasing priority::

    built-in defaults
    [tool.codecrew] in pyproject.toml   (or a codecrew.toml file)
    command-line flags

Recognised keys::

    profile = "full" | "quick"       quick skips mutation testing (G4), so it
                                     can never reach VERIFIED; it is for
                                     pre-commit, not for the final word
    min-coverage = 70                branch coverage threshold, percent
    min-mutation = 50                mutation score threshold, percent
    max-mutants = 40
    disable = ["G6"]                 gates to skip (they show as SKIP)
    non-blocking = ["G5"]            gates that report but never block
    exclude = ["migrations/*", "scripts/*"]
    install-dependencies = "auto"    auto | true | false (see below)
    sandbox = "auto"                 auto | docker | local
    test-timeout = 60                per-test seconds

``install-dependencies = "auto"`` installs a project's declared dependencies
unless the project was generated by CodeCrew: those packages were chosen by
a model, and installing one runs its build code on this machine. G8 vets
them first; a person decides whether to install.
"""

from __future__ import annotations

import fnmatch
import hashlib
import re
from dataclasses import dataclass, field
from pathlib import Path

from . import toml
from .config import WORK_DIR_NAME, GateConfig

PROFILES = {
    "full": (),
    "quick": ("G4",),
}

#: Optional-dependency groups that hold what the tests need.
_TEST_EXTRAS = ("test", "tests", "testing", "dev")
_REQUIREMENT_FILES = ("requirements.txt", "requirements-dev.txt",
                      "requirements-test.txt", "requirements_dev.txt",
                      "requirements_test.txt", "dev-requirements.txt",
                      "test-requirements.txt")
_SETTINGS = {"profile", "min-coverage", "min-mutation", "max-mutants", "disable",
             "non-blocking", "exclude", "install-dependencies", "sandbox",
             "test-timeout"}
_REQ_NAME = re.compile(r"^\s*([A-Za-z0-9][A-Za-z0-9._-]*)")


class ProjectConfigError(ValueError):
    """``[tool.codecrew]`` holds something CodeCrew cannot use."""


@dataclass
class Project:
    root: Path
    #: "src" for a src layout, "" when packages sit at the root.
    source_root: str = ""
    #: PEP 508 requirement strings declared by the project.
    dependencies: list[str] = field(default_factory=list)
    #: Requirement files found at the root, relative paths.
    requirement_files: list[str] = field(default_factory=list)
    #: The validated [tool.codecrew] table.
    settings: dict = field(default_factory=dict)
    #: Where the settings came from, for the report.
    settings_file: str | None = None
    #: True for workspaces CodeCrew generated (a spec or plan is present).
    generated: bool = False
    warnings: list[str] = field(default_factory=list)

    @classmethod
    def detect(cls, root: Path) -> "Project":
        root = root.resolve()
        project = cls(root=root)
        project.generated = (root / WORK_DIR_NAME / "spec.json").exists() or \
            (root / WORK_DIR_NAME / "plan.json").exists()

        pyproject = root / "pyproject.toml"
        data: dict = {}
        if pyproject.is_file():
            try:
                data = toml.load(pyproject)
            except (toml.TomlError, OSError, UnicodeDecodeError) as exc:
                project.warnings.append(
                    f"pyproject.toml could not be read ({exc}); using defaults")
        meta = data.get("project") if isinstance(data.get("project"), dict) else {}
        project.dependencies = _strings(meta.get("dependencies"))
        extras = meta.get("optional-dependencies")
        if isinstance(extras, dict):
            for group in _TEST_EXTRAS:
                project.dependencies += _strings(extras.get(group))
        # PEP 735 dependency groups.
        groups = data.get("dependency-groups")
        if isinstance(groups, dict):
            for group in _TEST_EXTRAS:
                project.dependencies += _strings(groups.get(group))

        project.requirement_files = [
            name for name in _REQUIREMENT_FILES if (root / name).is_file()]

        tool = data.get("tool") if isinstance(data.get("tool"), dict) else {}
        settings = tool.get("codecrew") if isinstance(tool.get("codecrew"), dict) else None
        if settings is not None:
            project.settings_file = "pyproject.toml [tool.codecrew]"
        elif (root / "codecrew.toml").is_file():
            try:
                settings = toml.load(root / "codecrew.toml")
                project.settings_file = "codecrew.toml"
            except (toml.TomlError, OSError) as exc:
                project.warnings.append(f"codecrew.toml could not be read ({exc})")
        project.settings = _validate(settings or {})

        if (root / "src").is_dir() and any(
                p.suffix == ".py" or (p / "__init__.py").exists()
                for p in (root / "src").iterdir()):
            project.source_root = "src"
        return project

    # -- derived ------------------------------------------------------------------

    def should_install(self) -> bool:
        choice = self.settings.get("install-dependencies", "auto")
        if choice == "auto":
            return not self.generated
        return bool(choice)

    def has_dependencies(self) -> bool:
        return bool(self.dependencies or self.requirement_files)

    def dependency_digest(self) -> str:
        """Changes when anything that decides the installed set changes."""
        digest = hashlib.sha256()
        for dep in sorted(set(self.dependencies)):
            digest.update(dep.encode())
        for name in self.requirement_files:
            digest.update(name.encode())
            digest.update((self.root / name).read_bytes())
        return digest.hexdigest()[:16]

    def install_args(self) -> list[str]:
        args = list(dict.fromkeys(self.dependencies))
        for name in self.requirement_files:
            args += ["-r", str(self.root / name)]
        return args

    def declared_names(self) -> set[str]:
        names = set()
        for dep in self.dependencies:
            match = _REQ_NAME.match(dep)
            if match:
                names.add(match.group(1).lower().replace("_", "-"))
        return names

    def is_excluded(self, rel_posix: str) -> bool:
        return any(fnmatch.fnmatch(rel_posix, pattern)
                   for pattern in self.settings.get("exclude", []))

    def apply(self, config: GateConfig) -> GateConfig:
        """Fold the project's settings into ``config`` (flags win later)."""
        s = self.settings
        t = config.thresholds
        if "min-coverage" in s:
            t.min_branch_coverage = float(s["min-coverage"])
        if "min-mutation" in s:
            t.min_mutation_score = float(s["min-mutation"])
        if "max-mutants" in s:
            t.max_mutants = int(s["max-mutants"])
        if "test-timeout" in s:
            t.test_timeout_s = int(s["test-timeout"])
        disabled = list(config.disabled) + list(s.get("disable", []))
        disabled += PROFILES[s.get("profile", "full")]
        config.disabled = tuple(dict.fromkeys(d.upper() for d in disabled))
        config.non_blocking = tuple(dict.fromkeys(
            [*config.non_blocking, *(g.upper() for g in s.get("non-blocking", []))]))
        if "sandbox" in s:
            config.sandbox = s["sandbox"]
        return config


def _strings(value) -> list[str]:
    if not isinstance(value, list):
        return []
    return [v.strip() for v in value if isinstance(v, str) and v.strip()]


def _gate_list(key: str, value) -> list[str]:
    if not isinstance(value, list) or not all(
            isinstance(v, str) and re.fullmatch(r"[Gg]\d", v) for v in value):
        raise ProjectConfigError(f"'{key}' must be a list of gate ids like [\"G4\"]")
    return [v.upper() for v in value]


def _validate(raw: dict) -> dict:
    unknown = sorted(set(raw) - _SETTINGS)
    if unknown:
        raise ProjectConfigError(
            f"unknown [tool.codecrew] setting(s): {', '.join(unknown)}; "
            f"known: {', '.join(sorted(_SETTINGS))}")
    out: dict = {}
    for key, value in raw.items():
        if key == "profile":
            if value not in PROFILES:
                raise ProjectConfigError(f"'profile' must be one of {', '.join(PROFILES)}")
            out[key] = value
        elif key in ("min-coverage", "min-mutation"):
            if isinstance(value, bool) or not isinstance(value, (int, float)) \
                    or not 0 <= value <= 100:
                raise ProjectConfigError(f"'{key}' must be a number from 0 to 100")
            out[key] = float(value)
        elif key in ("max-mutants", "test-timeout"):
            if isinstance(value, bool) or not isinstance(value, int) or value < 1:
                raise ProjectConfigError(f"'{key}' must be a positive integer")
            out[key] = value
        elif key in ("disable", "non-blocking"):
            out[key] = _gate_list(key, value)
        elif key == "exclude":
            if not isinstance(value, list) or not all(isinstance(v, str) for v in value):
                raise ProjectConfigError("'exclude' must be a list of glob patterns")
            out[key] = value
        elif key == "install-dependencies":
            if value not in ("auto", True, False):
                raise ProjectConfigError(
                    "'install-dependencies' must be \"auto\", true or false")
            out[key] = value
        elif key == "sandbox":
            if value not in ("auto", "docker", "local"):
                raise ProjectConfigError("'sandbox' must be auto, docker or local")
            out[key] = value
    return out
