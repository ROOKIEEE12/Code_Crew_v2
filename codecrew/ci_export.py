"""Export the gates as a GitHub Actions workflow.

A verdict computed once on the author's machine says nothing about the next
commit. The exported workflow re-runs the same deterministic gates on every
push and pull request, so a later hand edit (or a later AI edit) has to pass
them too. No model is involved in CI: it is the gate layer only.
"""

from __future__ import annotations

from pathlib import Path

DEFAULT_SOURCE = "git+https://github.com/ROOKIEEE12/Code_Crew_v2.git"
WORKFLOW_PATH = Path(".github") / "workflows" / "codecrew.yml"


def render_workflow(
    *,
    workspace: str = ".",
    source: str = DEFAULT_SOURCE,
    ref: str = "main",
    python: str = "3.12",
    disable: tuple[str, ...] = (),
    code_scanning: bool = False,
) -> str:
    """The workflow YAML. ``workspace`` is relative to the repository root."""
    workspace = workspace.strip().replace("\\", "/").rstrip("/") or "."
    if workspace.startswith("/") or ".." in workspace.split("/"):
        raise ValueError("workspace must be a path inside the repository")
    if any(ch in source + ref for ch in " \n\"'`$"):
        raise ValueError("source and ref must not contain spaces, quotes or '$'")
    if not python.replace(".", "").isdigit():
        raise ValueError(f"not a Python version: {python!r}")
    for gate in disable:
        if not (gate.startswith("G") and gate[1:].isdigit()):
            raise ValueError(f"not a gate id: {gate!r}")

    disable_arg = f" --disable {','.join(disable)}" if disable else ""
    evidence = f"{workspace}/.codecrew" if workspace != "." else ".codecrew"
    sarif_arg = "\n          --sarif codecrew.sarif" if code_scanning else ""
    permissions = "  contents: read\n" + (
        "  security-events: write  # upload findings to code scanning\n"
        if code_scanning else "")
    sarif_step = """
      # Findings appear as annotations on the pull request (code scanning).
      - name: Upload findings
        if: always()
        uses: github/codeql-action/upload-sarif@v3
        with:
          sarif_file: codecrew.sarif
          category: codecrew
""" if code_scanning else ""
    return f"""\
# Generated by `codecrew ci-export`. Re-runs CodeCrew's deterministic gates
# (syntax, tests, branch coverage, mutation, security, spec conformance,
# dependencies) on every push and pull request. No AI model runs here.
name: CodeCrew verification

on:
  push:
  pull_request:

permissions:
{permissions}
jobs:
  verify:
    runs-on: ubuntu-latest
    timeout-minutes: 30
    steps:
      - uses: actions/checkout@v4

      - uses: actions/setup-python@v5
        with:
          python-version: "{python}"

      # The gate tools and the project's dependency environment are
      # rebuilt only when the declared dependencies change.
      - uses: actions/cache@v4
        with:
          path: ~/.codecrew
          key: codecrew-${{{{ runner.os }}}}-py{python}-${{{{ hashFiles('**/pyproject.toml', '**/requirements*.txt') }}}}

      # Pin `{ref}` to a commit SHA for a reproducible verdict.
      - name: Install CodeCrew
        run: python -m pip install "codecrew @ {source}@{ref}"

      # The local sandbox isolates dependencies, not the host; on a
      # throwaway CI runner that is the right trade-off. The verdict and
      # every gate's evidence are written below.
      - name: Run the gates
        run: >-
          codecrew verify "{workspace}" --sandbox local{disable_arg}
          --json codecrew-report.json{sarif_arg}
          --markdown "$GITHUB_STEP_SUMMARY"
{sarif_step}
      - name: Upload evidence
        if: always()
        uses: actions/upload-artifact@v4
        with:
          name: codecrew-evidence
          path: |
            codecrew-report.json
            {evidence}/evidence/
          if-no-files-found: ignore
"""


def export_workflow(repo_root: Path, *, force: bool = False, **options) -> Path:
    target = repo_root / WORKFLOW_PATH
    if target.exists() and not force:
        raise FileExistsError(f"{target} exists; pass --force to overwrite it")
    text = render_workflow(**options)
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(text, encoding="utf-8")
    return target
