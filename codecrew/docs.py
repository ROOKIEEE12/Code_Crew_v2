"""The usage guide handed back with a build.

The synopsis gives this job to a Review/Documentation *agent*. It is done
deterministically instead, from the approved spec and the gate report, for
two reasons that both come from the project's one rule:

* a model writing prose after verification could describe behaviour the
  code does not have, and nothing would check it;
* every example printed here is one gate G7 actually executed, so the
  guide is exactly as trustworthy as the verdict printed at its top, and
  says so when it is not.

The file is written next to the code and never read by any gate.
"""

from __future__ import annotations

from pathlib import Path

from .agents import ProjectPlan, Spec
from .badges import FileBadge, Review
from .results import GateReport, Status

USAGE_FILE = "USAGE.md"


def render_usage(
    specs: list[Spec],
    report: GateReport | None,
    badges: list[FileBadge] | None = None,
    *,
    review: Review | None = None,
    plan: ProjectPlan | None = None,
) -> str:
    title = plan.summary if plan else (specs[0].summary if specs else "Usage")
    lines = [f"# {_one_line(title)}", ""]

    verdict = report.verdict() if report else "NOT VERIFIED"
    caveat = review.caveat() if review else None
    lines.append(f"**Verdict: {verdict}**" + (f" ({caveat})" if caveat else ""))
    lines.append("")
    lines.append(_example_status(report))
    lines.append("")
    lines.append("> Generated by CodeCrew from the approved specification. "
                 "No model wrote this page.")
    lines.append("")

    if plan and len(specs) > 1:
        lines += ["## Modules", ""]
        for module in plan.build_order():
            deps = f" (uses {', '.join(module.depends_on)})" if module.depends_on else ""
            lines.append(f"- `{module.name}`: {module.responsibility}{deps}")
        lines.append("")

    for spec in specs:
        lines += _render_spec(spec, heading="##" if len(specs) == 1 else "###",
                              multi=len(specs) > 1)

    if badges:
        lines += ["## Trust per file", "", "| File | Badge | Why |", "|---|---|---|"]
        for badge in badges:
            why = "; ".join(badge.reasons[:2]) or "every gate ran and passed"
            lines.append(f"| `{badge.path}` | {badge.badge} | {_cell(why)} |")
        lines.append("")

    lines += [
        "## Re-check it yourself",
        "",
        "```bash",
        "python -m pytest tests -q          # the generated tests",
        "python -m codecrew verify .        # every gate, with evidence",
        "```",
        "",
    ]
    return "\n".join(lines)


def write_usage(workspace: Path, text: str) -> Path:
    path = workspace / USAGE_FILE
    path.write_text(text, encoding="utf-8")
    return path


def _render_spec(spec: Spec, *, heading: str, multi: bool) -> list[str]:
    lines = []
    if multi:
        lines += [f"{heading} `{spec.module}`", "", spec.summary, ""]
    else:
        lines += [f"{heading} Module `{spec.module}`", "", spec.summary, ""]
    # Examples are evaluated in the module's namespace (that is how G7 runs
    # them), so they are shown after a from-import of every function.
    names = ", ".join(f.name for f in spec.functions)
    lines += ["```python", f"from {spec.module} import {names}", "```", ""]

    for func in spec.functions:
        lines += [f"{heading}# `{func.signature}`", "", func.description, ""]
        if func.raises:
            lines.append("Raises: " + ", ".join(f"`{r}`" for r in func.raises))
            lines.append("")
        if func.examples:
            lines.append("```python")
            for example in func.examples:
                lines.append(f">>> {example.call}")
                if example.raises is not None:
                    lines.append(f"Traceback (most recent call last): ... "
                                 f"{example.raises}")
                else:
                    lines.append(str(example.result))
            lines.append("```")
            lines.append("")

    for title, items in (("Constraints", spec.constraints),
                         ("Security properties", spec.security),
                         ("Decisions the requirement left open", spec.assumptions)):
        if items:
            lines += [f"**{title}**", ""]
            lines += [f"- {item}" for item in items]
            lines.append("")
    return lines


def _example_status(report: GateReport | None) -> str:
    g7 = None if report is None else next(
        (r for r in report.results if r.gate_id == "G7"), None)
    if g7 is None:
        return ("The examples below come from the specification and were "
                "**not** executed (spec conformance did not run).")
    if g7.status is Status.PASS:
        return ("Every example below was executed against the code by the "
                "spec-conformance gate (G7) and matched.")
    return (f"The examples below come from the specification, but the "
            f"spec-conformance gate reported **{g7.status.value}**: "
            f"{g7.summary}. Do not rely on them until it passes.")


def _one_line(text: str) -> str:
    return " ".join(text.split())[:120]


def _cell(text: str) -> str:
    return _one_line(text).replace("|", "\\|")
